package com.ae.apps.lib.sample.features.dev;

import android.Manifest;
import android.annotation.TargetApi;
import android.content.ContentProviderOperation;
import android.content.ContentResolver;
import android.database.Cursor;
import android.os.Build;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.provider.ContactsContract;
import android.provider.ContactsContract.CommonDataKinds.Email;
import android.provider.ContactsContract.CommonDataKinds.Note;
import android.provider.ContactsContract.CommonDataKinds.Phone;
import android.provider.ContactsContract.CommonDataKinds.StructuredName;
import android.view.View;
import android.widget.Button;
import android.widget.ProgressBar;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.appcompat.app.AppCompatActivity;

import com.ae.apps.lib.permissions.PermissionsAwareComponent;
import com.ae.apps.lib.permissions.RuntimePermissionChecker;
import com.ae.apps.lib.sample.BuildConfig;
import com.ae.apps.lib.sample.R;
import com.ae.apps.lib.sample.utils.DeviceUtils;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Locale;
import java.util.Random;
import java.util.Set;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

/**
 * Developer tool that fills the device's address book with random contacts, so the
 * Contacts API and Multi Contact Picker samples have data to work with.
 *
 * <p>This class lives in the debug source set and is only reachable when
 * {@code BuildConfig.FEATURE_CONTACT_GENERATOR} is on and the app runs on an emulator.
 * Every contact it creates carries a marker note, so they can be removed again
 * without touching real contacts.</p>
 */
public class ContactGeneratorActivity extends AppCompatActivity implements PermissionsAwareComponent {

    private static final int PERMISSION_CODE = 3000;
    private static final int CONTACTS_TO_CREATE = 100;
    /** Marker stored in a Note on each generated contact; used to find them for removal */
    private static final String GENERATED_MARKER = "Generated by libAeApps sample";

    private static final String[] FIRST_NAMES = {
            "Aarav", "Aiden", "Amelia", "Ananya", "Ben", "Carlos", "Chloe", "Daisy", "Diana", "Diego",
            "Elena", "Ethan", "Fatima", "Grace", "Hana", "Isaac", "Isla", "James", "Jesse", "Kai",
            "Layla", "Leo", "Lucia", "Maya", "Martin", "Matt", "Mei", "Nina", "Noah", "Olivia",
            "Omar", "Priya", "Quinn", "Ravi", "Rosa", "Sam", "Sara", "Scott", "Tariq", "Uma",
            "Victor", "Wen", "Yara", "Zane"
    };

    private static final String[] LAST_NAMES = {
            "Adams", "Brown", "Burns", "Chen", "Costa", "Das", "Elliot", "Fernandez", "Forster", "Fox",
            "Garcia", "Gibson", "Haddad", "Ito", "Johnson", "Kim", "Kumar", "Lopez", "Martin", "Menon",
            "Nair", "Nguyen", "Okafor", "Patel", "Perry", "Rossi", "Sato", "Silva", "Smith", "Taylor",
            "Wang", "Whitehurst", "Williams", "Young"
    };

    private static final String[] EMAIL_DOMAINS = {"example.com", "example.org", "example.net"};

    private final ExecutorService executor = Executors.newSingleThreadExecutor();
    private final Handler mainHandler = new Handler(Looper.getMainLooper());
    private final Random random = new Random();

    private RuntimePermissionChecker permissionChecker;

    private View permissionsLayout;
    private View generatorLayout;
    private Button generateButton;
    private Button removeButton;
    private ProgressBar progressBar;
    private TextView statusText;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        // Guard against the screen being started directly (e.g. via adb) when it should not run
        if (!BuildConfig.FEATURE_CONTACT_GENERATOR || !DeviceUtils.isEmulator()) {
            finish();
            return;
        }

        setContentView(R.layout.activity_contact_generator);

        permissionsLayout = findViewById(R.id.layout_need_permissions);
        generatorLayout = findViewById(R.id.layout_generator);
        generateButton = findViewById(R.id.btn_generate_contacts);
        removeButton = findViewById(R.id.btn_remove_contacts);
        progressBar = findViewById(R.id.progress_generate);
        statusText = findViewById(R.id.text_generator_status);

        generateButton.setText(getString(R.string.str_btn_generate_contacts, CONTACTS_TO_CREATE));
        progressBar.setMax(CONTACTS_TO_CREATE);

        findViewById(R.id.btn_request_permissions).setOnClickListener(v -> requestForPermissions());
        generateButton.setOnClickListener(v -> generateContacts());
        removeButton.setOnClickListener(v -> removeGeneratedContacts());

        permissionChecker = RuntimePermissionChecker.newInstance(this);
        permissionChecker.checkPermissions();
    }

    @Override
    protected void onDestroy() {
        super.onDestroy();
        executor.shutdownNow();
    }

    // ---------------------------------------------------------------------------------------------
    // Permissions
    // ---------------------------------------------------------------------------------------------

    @Override
    public String[] requiredPermissions() {
        return new String[]{
                Manifest.permission.READ_CONTACTS,
                Manifest.permission.WRITE_CONTACTS
        };
    }

    @Override
    @TargetApi(Build.VERSION_CODES.M)
    public void requestForPermissions() {
        requestPermissions(requiredPermissions(), PERMISSION_CODE);
    }

    @Override
    public void onRequestPermissionsResult(int requestCode, @NonNull String[] permissions, @NonNull int[] grantResults) {
        if (requestCode == PERMISSION_CODE) {
            permissionChecker.handlePermissionsResult(permissions, grantResults);
        } else {
            super.onRequestPermissionsResult(requestCode, permissions, grantResults);
        }
    }

    @Override
    public void onPermissionsRequired() {
        showPermissionsView(true);
    }

    @Override
    public void onPermissionsGranted() {
        showPermissionsView(false);
    }

    @Override
    public void onPermissionsDenied() {
        showPermissionsView(true);
    }

    private void showPermissionsView(boolean show) {
        permissionsLayout.setVisibility(show ? View.VISIBLE : View.GONE);
        generatorLayout.setVisibility(show ? View.GONE : View.VISIBLE);
    }

    // ---------------------------------------------------------------------------------------------
    // Generate / remove
    // ---------------------------------------------------------------------------------------------

    private void generateContacts() {
        setBusy(true);
        progressBar.setProgress(0);
        statusText.setText(R.string.str_generating_contacts);
        final long startTime = System.currentTimeMillis();

        executor.execute(() -> {
            ContentResolver resolver = getContentResolver();
            int created = 0;
            String error = null;
            try {
                for (int i = 0; i < CONTACTS_TO_CREATE; i++) {
                    resolver.applyBatch(ContactsContract.AUTHORITY, buildContactOperations());
                    created++;
                    final int progress = created;
                    mainHandler.post(() -> progressBar.setProgress(progress));
                }
            } catch (Exception e) {
                error = e.getMessage();
            }

            final int total = created;
            final String failure = error;
            final long elapsed = System.currentTimeMillis() - startTime;
            mainHandler.post(() -> {
                if (isFinishing()) return;
                setBusy(false);
                if (null == failure) {
                    statusText.setText(getString(R.string.str_generated_contacts, total, elapsed));
                } else {
                    statusText.setText(getString(R.string.str_generate_failed, total, failure));
                }
            });
        });
    }

    /**
     * Builds the operations that insert one local (no account) contact with a name,
     * a mobile number, an email address and the marker note.
     */
    private ArrayList<ContentProviderOperation> buildContactOperations() {
        String firstName = FIRST_NAMES[random.nextInt(FIRST_NAMES.length)];
        String lastName = LAST_NAMES[random.nextInt(LAST_NAMES.length)];
        // The 555 exchange is conventionally used for fictional numbers
        String phone = String.format(Locale.US, "+1 %03d 555 %04d",
                200 + random.nextInt(800), random.nextInt(10000));
        String email = String.format(Locale.US, "%s.%s%d@%s",
                firstName.toLowerCase(Locale.US), lastName.toLowerCase(Locale.US),
                random.nextInt(100), EMAIL_DOMAINS[random.nextInt(EMAIL_DOMAINS.length)]);

        ArrayList<ContentProviderOperation> ops = new ArrayList<>();
        ops.add(ContentProviderOperation.newInsert(ContactsContract.RawContacts.CONTENT_URI)
                .withValue(ContactsContract.RawContacts.ACCOUNT_TYPE, null)
                .withValue(ContactsContract.RawContacts.ACCOUNT_NAME, null)
                .build());
        ops.add(dataInsert(StructuredName.CONTENT_ITEM_TYPE)
                .withValue(StructuredName.GIVEN_NAME, firstName)
                .withValue(StructuredName.FAMILY_NAME, lastName)
                .build());
        ops.add(dataInsert(Phone.CONTENT_ITEM_TYPE)
                .withValue(Phone.NUMBER, phone)
                .withValue(Phone.TYPE, Phone.TYPE_MOBILE)
                .build());
        ops.add(dataInsert(Email.CONTENT_ITEM_TYPE)
                .withValue(Email.ADDRESS, email)
                .withValue(Email.TYPE, Email.TYPE_HOME)
                .build());
        ops.add(dataInsert(Note.CONTENT_ITEM_TYPE)
                .withValue(Note.NOTE, GENERATED_MARKER)
                .build());
        return ops;
    }

    private static ContentProviderOperation.Builder dataInsert(String mimeType) {
        return ContentProviderOperation.newInsert(ContactsContract.Data.CONTENT_URI)
                .withValueBackReference(ContactsContract.Data.RAW_CONTACT_ID, 0)
                .withValue(ContactsContract.Data.MIMETYPE, mimeType);
    }

    /**
     * Deletes only the contacts that carry the marker note added by {@link #generateContacts()}.
     */
    private void removeGeneratedContacts() {
        setBusy(true);
        statusText.setText(R.string.str_removing_contacts);

        executor.execute(() -> {
            ContentResolver resolver = getContentResolver();
            int removed = 0;
            String error = null;
            try {
                Set<Long> rawContactIds = new HashSet<>();
                try (Cursor cursor = resolver.query(ContactsContract.Data.CONTENT_URI,
                        new String[]{ContactsContract.Data.RAW_CONTACT_ID},
                        ContactsContract.Data.MIMETYPE + " = ? AND " + Note.NOTE + " = ?",
                        new String[]{Note.CONTENT_ITEM_TYPE, GENERATED_MARKER},
                        null)) {
                    while (null != cursor && cursor.moveToNext()) {
                        rawContactIds.add(cursor.getLong(0));
                    }
                }

                ArrayList<ContentProviderOperation> ops = new ArrayList<>();
                for (Long id : rawContactIds) {
                    ops.add(ContentProviderOperation.newDelete(ContactsContract.RawContacts.CONTENT_URI)
                            .withSelection(ContactsContract.RawContacts._ID + " = ?",
                                    new String[]{String.valueOf(id)})
                            .build());
                }
                if (!ops.isEmpty()) {
                    resolver.applyBatch(ContactsContract.AUTHORITY, ops);
                }
                removed = rawContactIds.size();
            } catch (Exception e) {
                error = e.getMessage();
            }

            final int total = removed;
            final String failure = error;
            mainHandler.post(() -> {
                if (isFinishing()) return;
                setBusy(false);
                if (null == failure) {
                    statusText.setText(getString(R.string.str_removed_contacts, total));
                } else {
                    statusText.setText(getString(R.string.str_remove_failed, failure));
                }
            });
        });
    }

    private void setBusy(boolean busy) {
        generateButton.setEnabled(!busy);
        removeButton.setEnabled(!busy);
        progressBar.setVisibility(busy ? View.VISIBLE : View.INVISIBLE);
    }
}
